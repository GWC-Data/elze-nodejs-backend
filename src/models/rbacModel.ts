import { quoteIdentifier, quoteQualified } from '../tools/sql';
import { USER_STATUS } from '../constants/statuses';

const q = quoteIdentifier;

const ACCESS_SCHEMA = 'access_control';
const LEGACY_SCHEMA = 'legacy_rbac';

const a = (name: string) => quoteQualified(ACCESS_SCHEMA, name);

const T = {
  companies: q('companies'),
  users: q('users'),
  groups: q('groups'),
  groupUsers: q('group_users'),
  dashboards: q('dashboards'),
  refreshTokens: q('refresh_tokens'),
  userTokens: q('user_tokens'),
  loginAttempts: q('login_attempts'),
  rbacRepairs: q('rbac_repairs'),
  auditLogs: q('audit_logs'),

  features: a('features'),
  permissions: a('permissions'),
  accessLevels: a('access_levels'),
  roles: a('roles'),
  rolePermissions: a('role_permissions'),
  companyFeatures: a('company_features'),
  userRoles: a('user_roles'),
  userPermissions: a('user_permissions'),
  userDataScopes: a('user_data_scopes'),
  companyDashboards: a('company_dashboards'),
  dashboardUserAccess: a('dashboard_user_access'),
  dashboardGroupAccess: a('dashboard_group_access'),
  contextUserAccess: a('context_user_access'),
  contextGroupAccess: a('context_group_access'),
};

const V = {
  userEffectivePermissions: a('user_effective_permissions'),
  userResourceAccess: a('user_resource_access'),
  userAccessSummary: a('user_access_summary'),
  rolePermissionSummary: a('role_permission_summary'),
  companyFeatureSummary: a('company_feature_summary'),
};

const STATUS_LIST = [USER_STATUS.PENDING, USER_STATUS.ACTIVE, USER_STATUS.DISABLED]
  .map((s) => `'${s}'`)
  .join(',');

const TABLES = [
  `CREATE TABLE IF NOT EXISTS ${T.companies} (
     id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     name         VARCHAR(150) NOT NULL,
     slug         VARCHAR(64)  NOT NULL,
     active       BOOLEAN      NOT NULL DEFAULT TRUE,
     created_by   INTEGER      NULL,
     created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
     CONSTRAINT uq_companies_slug UNIQUE (slug),
     CONSTRAINT uq_companies_name UNIQUE (name)
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.users} (
     id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     company_id           INTEGER      NULL REFERENCES ${T.companies} (id) ON DELETE CASCADE,
     username             VARCHAR(50)  NOT NULL,
     email                VARCHAR(190) NOT NULL,
     display_name         VARCHAR(120) NULL,
     password_hash        VARCHAR(100) NULL,
     status               VARCHAR(16)  NOT NULL DEFAULT 'pending',
     must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
     last_login_at        TIMESTAMPTZ  NULL,
     created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
     CONSTRAINT uq_users_username UNIQUE (username),
     CONSTRAINT uq_users_email    UNIQUE (email),
     CONSTRAINT chk_users_status  CHECK (status IN (${STATUS_LIST}))
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.groups} (
     id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     company_id INTEGER      NOT NULL REFERENCES ${T.companies} (id) ON DELETE CASCADE,
     name       VARCHAR(100) NOT NULL,
     active     BOOLEAN      NOT NULL DEFAULT TRUE,
     creator_id INTEGER      NULL REFERENCES ${T.users} (id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
     CONSTRAINT uq_groups_company_name UNIQUE (company_id, name)
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.groupUsers} (
     group_id   INTEGER     NOT NULL REFERENCES ${T.groups} (id) ON DELETE CASCADE,
     user_id    INTEGER     NOT NULL REFERENCES ${T.users} (id) ON DELETE CASCADE,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     PRIMARY KEY (group_id, user_id)
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.dashboards} (
     id           VARCHAR(64)  PRIMARY KEY,
     title        VARCHAR(150) NOT NULL,
     description  TEXT         NULL,
     company_id   INTEGER      NULL REFERENCES ${T.companies} (id) ON DELETE CASCADE,
     created_by   INTEGER      NULL REFERENCES ${T.users} (id) ON DELETE SET NULL,
     spec         JSONB        NOT NULL,
     created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
     updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.refreshTokens} (
     id             UUID        PRIMARY KEY,
     family_id      UUID        NOT NULL,
     user_id        INTEGER     NOT NULL REFERENCES ${T.users} (id) ON DELETE CASCADE,
     token_hash     CHAR(64)    NOT NULL,
     issued_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
     expires_at     TIMESTAMPTZ NOT NULL,
     revoked_at     TIMESTAMPTZ NULL,
     revoked_reason VARCHAR(40) NULL,
     replaced_by    UUID        NULL,
     CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.userTokens} (
     id          UUID        PRIMARY KEY,
     user_id     INTEGER     NOT NULL REFERENCES ${T.users} (id) ON DELETE CASCADE,
     purpose     VARCHAR(24) NOT NULL,
     token_hash  CHAR(64)    NOT NULL,
     expires_at  TIMESTAMPTZ NOT NULL,
     consumed_at TIMESTAMPTZ NULL,
     created_by  INTEGER     NULL,
     created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
     CONSTRAINT uq_user_tokens_hash UNIQUE (token_hash)
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.rbacRepairs} (
     id         VARCHAR(64) PRIMARY KEY,
     applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.loginAttempts} (
     identifier        VARCHAR(190) PRIMARY KEY,
     attempts          INTEGER      NOT NULL DEFAULT 0,
     window_started_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
     locked_until      TIMESTAMPTZ  NULL
   )`,

  `CREATE TABLE IF NOT EXISTS ${T.auditLogs} (
     id               BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
     ts               TIMESTAMPTZ  NOT NULL DEFAULT now(),
     event            VARCHAR(64)  NOT NULL,
     actor_id         INTEGER      NULL,
     actor            VARCHAR(190) NULL,
     actor_company_id INTEGER      NULL,
     company_id       INTEGER      NULL,
     target_user_id   INTEGER      NULL,
     detail           JSONB        NOT NULL DEFAULT '{}'::jsonb
   )`,
];

const INDEXES = [
  `CREATE INDEX IF NOT EXISTS idx_users_company ON ${T.users} (company_id)`,
  `CREATE INDEX IF NOT EXISTS idx_groups_creator ON ${T.groups} (creator_id)`,
  `CREATE INDEX IF NOT EXISTS idx_group_users_user ON ${T.groupUsers} (user_id)`,
  `CREATE INDEX IF NOT EXISTS idx_dashboards_company ON ${T.dashboards} (company_id)`,
  `CREATE INDEX IF NOT EXISTS idx_dashboards_creator ON ${T.dashboards} (created_by)`,
  `CREATE INDEX IF NOT EXISTS idx_refresh_tokens_family ON ${T.refreshTokens} (family_id)`,
  `CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user ON ${T.refreshTokens} (user_id)`,
  `CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expiry ON ${T.refreshTokens} (expires_at)`,
  `CREATE INDEX IF NOT EXISTS idx_user_tokens_user ON ${T.userTokens} (user_id, purpose)`,
  `CREATE INDEX IF NOT EXISTS idx_audit_logs_ts ON ${T.auditLogs} (ts DESC)`,
  `CREATE INDEX IF NOT EXISTS idx_audit_logs_company ON ${T.auditLogs} (company_id, ts DESC)`,
  `CREATE INDEX IF NOT EXISTS idx_audit_logs_actor ON ${T.auditLogs} (actor_id, ts DESC)`,
  `CREATE INDEX IF NOT EXISTS idx_audit_logs_target_user ON ${T.auditLogs} (target_user_id, ts DESC)`,
];

export { ACCESS_SCHEMA, LEGACY_SCHEMA, T, V, TABLES, INDEXES };
